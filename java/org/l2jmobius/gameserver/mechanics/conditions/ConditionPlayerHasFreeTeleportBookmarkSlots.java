package org.l2jmobius.gameserver.mechanics.conditions;

import org.l2jmobius.gameserver.entity.actor.Creature;
import org.l2jmobius.gameserver.entity.actor.Player;
import org.l2jmobius.gameserver.entity.item.ItemTemplate;
import org.l2jmobius.gameserver.mechanics.skill.Skill;
import org.l2jmobius.gameserver.network.SystemMessageId;

/**
 * Checks if a {@code Player} has any available slots for teleport bookmarks.<br>
 * This condition is used to verify space in the player's bookmark inventory.
 * @author Sdw
 */
public class ConditionPlayerHasFreeTeleportBookmarkSlots extends Condition
{
	private final int _teleportBookmarkSlots;
	
	/**
	 * Checks if a player has enough free slots for teleport bookmarks.<br>
	 * This condition is used to verify available space before creating a bookmark.
	 * @param teleportBookmarkSlots The required number of free slots needed.
	 */
	public ConditionPlayerHasFreeTeleportBookmarkSlots(int teleportBookmarkSlots)
	{
		_teleportBookmarkSlots = teleportBookmarkSlots;
	}
	
	/**
	 * Checks if the player has enough free teleport bookmark slots.<br>
	 * It verifies that adding the required amount does not exceed the maximum limit of 18.<br>
	 * If the limit is reached, it sends a system message to the player.
	 * @param effector The {@code Creature} performing the action.
	 * @param effected The {@code Creature} receiving the action.
	 * @param skill The {@code Skill} being used.
	 * @param item The {@code ItemTemplate} involved in the action.
	 * @return {@code true} if there is enough space, otherwise {@code false}.
	 */
	@Override
	public boolean testImpl(Creature effector, Creature effected, Skill skill, ItemTemplate item)
	{
		final Player player = effector.asPlayer();
		if (player == null)
		{
			return false;
		}
		
		if ((player.getBookMarkSlot() + _teleportBookmarkSlots) > 18)
		{
			player.sendPacket(SystemMessageId.YOU_HAVE_REACHED_THE_MAXIMUM_NUMBER_OF_MY_TELEPORT_SLOTS_OR_USE_CONDITIONS_ARE_NOT_OBSERVED);
			return false;
		}
		
		return true;
	}
}
