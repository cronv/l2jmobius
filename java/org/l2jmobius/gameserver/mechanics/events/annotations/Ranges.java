package org.l2jmobius.gameserver.mechanics.events.annotations;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * This annotation is used to define range-based constraints for game mechanics.<br>
 * It allows developers to specify valid numerical boundaries for specific methods.<br>
 * Use {@code Ranges} to ensure that values stay within the intended limits.
 * @author UnAfraid
 */
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.METHOD)
public @interface Ranges
{
	Range[] value();
}
