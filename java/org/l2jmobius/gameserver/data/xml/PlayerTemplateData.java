package org.l2jmobius.gameserver.data.xml;

import java.io.File;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.logging.Logger;

import org.w3c.dom.Document;
import org.w3c.dom.NamedNodeMap;
import org.w3c.dom.Node;

import org.l2jmobius.commons.util.IXmlReader;
import org.l2jmobius.gameserver.entity.Location;
import org.l2jmobius.gameserver.entity.actor.enums.player.PlayerClass;
import org.l2jmobius.gameserver.entity.actor.templates.PlayerTemplate;
import org.l2jmobius.gameserver.util.StatSet;

/**
 * This class handles the loading and parsing of player template data from XML files.<br>
 * It maps configuration values to {@code PlayerTemplate} objects for use in the game server.
 * @author Forsaiken, Mobius
 */
public class PlayerTemplateData implements IXmlReader
{
	private static final Logger LOGGER = Logger.getLogger(PlayerTemplateData.class.getName());
	
	private final Map<PlayerClass, PlayerTemplate> _playerTemplates = new ConcurrentHashMap<>();
	final AtomicInteger _levelUpGainCount = new AtomicInteger();
	final AtomicInteger _autoGeneratedCount = new AtomicInteger();
	
	/**
	 * Initializes a new instance of {@code PlayerTemplateData}.<br>
	 * This constructor automatically calls the {@code load} method.<br>
	 * It prepares the data for use by the game server.
	 */
	protected PlayerTemplateData()
	{
		load();
	}
	
	/**
	 * Loads all player templates from the data directory.<br>
	 * This method clears existing data and resets internal counters.<br>
	 * It then parses the template files and logs the results.
	 */
	@Override
	public void load()
	{
		_playerTemplates.clear();
		_levelUpGainCount.set(0);
		_autoGeneratedCount.set(0);
		parseDatapackDirectory("data/stats/players/templates", true);
		
		final String simpleName = getClass().getSimpleName();
		LOGGER.info(simpleName + ": Loaded " + _playerTemplates.size() + " player templates.");
		LOGGER.info(simpleName + ": Loaded " + _levelUpGainCount.get() + " level up gain records.");
		if (_autoGeneratedCount.get() > 0)
		{
			LOGGER.info(simpleName + ": Generated " + _autoGeneratedCount.get() + " level up gain records.");
		}
	}
	
	/**
	 * Parses the player template data from an XML document.<br>
	 * This method populates the internal template map using the provided file and document.<br>
	 * It handles static data, level up gains, and auto-generates missing stats.
	 * @param document The {@code Document} object containing the XML content.
	 * @param file The {@code File} associated with the parsed document.
	 */
	@Override
	public void parseDocument(Document document, File file)
	{
		final int maxLevel = ExperienceData.getInstance().getMaxLevel();
		
		NamedNodeMap attributes;
		int classId = 0;
		for (Node n = document.getFirstChild(); n != null; n = n.getNextSibling())
		{
			if ("list".equalsIgnoreCase(n.getNodeName()))
			{
				for (Node d = n.getFirstChild(); d != null; d = d.getNextSibling())
				{
					final String dName = d.getNodeName();
					if ("classId".equalsIgnoreCase(dName))
					{
						classId = Integer.parseInt(d.getTextContent());
					}
					else if ("staticData".equalsIgnoreCase(dName))
					{
						final StatSet set = new StatSet();
						set.set("classId", classId);
						final List<Location> creationPoints = new ArrayList<>();
						for (Node nd = d.getFirstChild(); nd != null; nd = nd.getNextSibling())
						{
							final String ndName = nd.getNodeName();
							// Skip odd nodes.
							if (ndName.equals("#text"))
							{
								continue;
							}
							
							if (nd.getChildNodes().getLength() > 1)
							{
								final boolean isCollisionMale = ndName.equalsIgnoreCase("collisionMale");
								for (Node cnd = nd.getFirstChild(); cnd != null; cnd = cnd.getNextSibling())
								{
									final String cndName = cnd.getNodeName();
									// Use CreatureTemplate(superclass) fields for male collision height and collision radius.
									if (isCollisionMale)
									{
										if (cndName.equalsIgnoreCase("radius"))
										{
											set.set("collision_radius", cnd.getTextContent());
										}
										else if (cndName.equalsIgnoreCase("height"))
										{
											set.set("collision_height", cnd.getTextContent());
										}
									}
									
									if ("node".equalsIgnoreCase(cndName))
									{
										attributes = cnd.getAttributes();
										creationPoints.add(new Location(parseInteger(attributes, "x"), parseInteger(attributes, "y"), parseInteger(attributes, "z")));
									}
									else if ("walk".equalsIgnoreCase(cndName))
									{
										set.set("baseWalkSpd", cnd.getTextContent());
									}
									else if ("run".equalsIgnoreCase(cndName))
									{
										set.set("baseRunSpd", cnd.getTextContent());
									}
									else if ("slowSwim".equals(cndName))
									{
										set.set("baseSwimWalkSpd", cnd.getTextContent());
									}
									else if ("fastSwim".equals(cndName))
									{
										set.set("baseSwimRunSpd", cnd.getTextContent());
									}
									else if (!cndName.equals("#text"))
									{
										set.set(ndName + cndName, cnd.getTextContent());
									}
								}
							}
							else
							{
								set.set(ndName, nd.getTextContent());
							}
						}
						
						// Calculate total pdef and mdef from parts.
						set.set("basePDef", set.getInt("basePDefchest", 0) + set.getInt("basePDeflegs", 0) + set.getInt("basePDefhead", 0) + set.getInt("basePDeffeet", 0) + set.getInt("basePDefgloves", 0) + set.getInt("basePDefunderwear", 0) + set.getInt("basePDefcloak", 0) + set.getInt("basePDefhair", 0));
						set.set("baseMDef", set.getInt("baseMDefrear", 0) + set.getInt("baseMDeflear", 0) + set.getInt("baseMDefrfinger", 0) + set.getInt("baseMDefrfinger", 0) + set.getInt("baseMDefneck", 0));
						_playerTemplates.put(PlayerClass.getPlayerClass(classId), new PlayerTemplate(set, creationPoints));
					}
					else if ("lvlUpgainData".equalsIgnoreCase(dName))
					{
						int level = 0;
						final PlayerTemplate template = _playerTemplates.get(PlayerClass.getPlayerClass(classId));
						for (Node lvlNode = d.getFirstChild(); lvlNode != null; lvlNode = lvlNode.getNextSibling())
						{
							if ("level".equalsIgnoreCase(lvlNode.getNodeName()))
							{
								attributes = lvlNode.getAttributes();
								level = parseInteger(attributes, "val");
								if (level > (maxLevel - 1))
								{
									return;
								}
								
								for (Node valNode = lvlNode.getFirstChild(); valNode != null; valNode = valNode.getNextSibling())
								{
									final String nodeName = valNode.getNodeName();
									if (nodeName.startsWith("hp") || nodeName.startsWith("mp") || nodeName.startsWith("cp"))
									{
										template.setUpgainValue(nodeName, level, Double.parseDouble(valNode.getTextContent()));
										_levelUpGainCount.incrementAndGet();
									}
								}
							}
						}
						
						// Generate missing stats automatically.
						while (level < (maxLevel - 1))
						{
							level++;
							_autoGeneratedCount.incrementAndGet();
							final double hpM1 = template.getBaseHpMax(level - 1);
							template.setUpgainValue("hp", level, (((hpM1 * level) / (level - 1)) + ((hpM1 * (level + 1)) / (level - 1))) / 2);
							final double mpM1 = template.getBaseMpMax(level - 1);
							template.setUpgainValue("mp", level, (((mpM1 * level) / (level - 1)) + ((mpM1 * (level + 1)) / (level - 1))) / 2);
							final double cpM1 = template.getBaseCpMax(level - 1);
							template.setUpgainValue("cp", level, (((cpM1 * level) / (level - 1)) + ((cpM1 * (level + 1)) / (level - 1))) / 2);
							final double hpRegM1 = template.getBaseHpRegen(level - 1);
							final double hpRegM2 = template.getBaseHpRegen(level - 2);
							template.setUpgainValue("hpRegen", level, (hpRegM1 * 2) - hpRegM2);
							final double mpRegM1 = template.getBaseMpRegen(level - 1);
							final double mpRegM2 = template.getBaseMpRegen(level - 2);
							template.setUpgainValue("mpRegen", level, (mpRegM1 * 2) - mpRegM2);
							final double cpRegM1 = template.getBaseCpRegen(level - 1);
							final double cpRegM2 = template.getBaseCpRegen(level - 2);
							template.setUpgainValue("cpRegen", level, (cpRegM1 * 2) - cpRegM2);
						}
					}
				}
			}
		}
	}
	
	/**
	 * Retrieves the {@code PlayerTemplate} for a specific player class.<br>
	 * This method looks up the template in the internal cache.
	 * @param playerClass The {@code PlayerClass} to search for.
	 * @return The corresponding {@code PlayerTemplate} or {@code null} if not found.
	 */
	public PlayerTemplate getTemplate(PlayerClass playerClass)
	{
		return _playerTemplates.get(playerClass);
	}
	
	/**
	 * Retrieves a {@code PlayerTemplate} based on the provided class ID.<br>
	 * This method looks up the template in the internal cache.
	 * @param classId The unique identifier for the player class.
	 * @return The {@code PlayerTemplate} associated with the given ID, or {@code null} if not found.
	 */
	public PlayerTemplate getTemplate(int classId)
	{
		return _playerTemplates.get(PlayerClass.getPlayerClass(classId));
	}
	
	/**
	 * Retrieves the singleton instance of {@code PlayerTemplateData}.<br>
	 * Use this method to access the global data manager.
	 * @return The single instance of {@code PlayerTemplateData}.
	 */
	public static PlayerTemplateData getInstance()
	{
		return SingletonHolder.INSTANCE;
	}
	
	private static class SingletonHolder
	{
		protected static final PlayerTemplateData INSTANCE = new PlayerTemplateData();
	}
}
